/// @brief Tells whether a code point is a combining mark, the accents of text written decomposed ("e" followed
/// by U+0301 instead of "é"), as macOS writes file names.
static bool is_combining_mark(char32_t c)
{
    return (c >= 0x0300 && c <= 0x036F) || (c >= 0x0483 && c <= 0x0487) || (c >= 0x1AB0 && c <= 0x1AFF) || (c >= 0x1DC0 && c <= 0x1DFF) ||
        (c >= 0x20D0 && c <= 0x20FF) || (c >= 0xFE20 && c <= 0xFE2F);
}

/// @brief The letter without its accents, for a small letter (see to_lower); others come back as they are.
static char32_t to_plain(char32_t c)
{
    if(c < 0xE0)
        return c;
    const plain_run *end = std::end(plain_runs);
    const plain_run *run = std::lower_bound(std::begin(plain_runs), end, c,
        [](const plain_run &r, char32_t value) { return r.last < value; });
    if(run == end || c < run->first || (c - run->first) % run->step != 0)
        return c;
    return run->plain;
}

static void append_utf8(std::string &out, char32_t c)
{
    if(c < 0x80)
        out += static_cast<char>(c);
    else if(c < 0x800)
    {
        out += static_cast<char>(0xC0 | (c >> 6));
        out += static_cast<char>(0x80 | (c & 0x3F));
    }
    else if(c < 0x10000)
    {
        out += static_cast<char>(0xE0 | (c >> 12));
        out += static_cast<char>(0x80 | ((c >> 6) & 0x3F));
        out += static_cast<char>(0x80 | (c & 0x3F));
    }
    else
    {
        out += static_cast<char>(0xF0 | (c >> 18));
        out += static_cast<char>(0x80 | ((c >> 12) & 0x3F));
        out += static_cast<char>(0x80 | ((c >> 6) & 0x3F));
        out += static_cast<char>(0x80 | (c & 0x3F));
    }
}

/// @param plain Whether accents go too.
static std::string fold(const std::string &utf8, bool plain)
{
    std::string out;
    out.reserve(utf8.size());
    for(std::size_t i = 0; i < utf8.size(); )
    {
        unsigned char lead = static_cast<unsigned char>(utf8[i]);
        if(lead < 0x80)
        {
            out += static_cast<char>(lead >= 'A' && lead <= 'Z' ? lead + 32 : lead);
            i++;
            continue;
        }
        // Decode one sequence; anything malformed (stray continuation byte, cut short, overlong) is copied.
        int length = lead >= 0xF0 && lead < 0xF5 ? 4 : lead >= 0xE0 ? 3 : lead >= 0xC2 && lead < 0xE0 ? 2 : 0;
        if(lead >= 0xF5)
            length = 0;
        char32_t c = length == 2 ? lead & 0x1F : length == 3 ? lead & 0x0F : lead & 0x07;
        bool valid = length > 0 && i + length <= utf8.size();
        for(int k = 1; valid && k < length; k++)
        {
            unsigned char next = static_cast<unsigned char>(utf8[i + k]);
            valid = (next & 0xC0) == 0x80;
            c = (c << 6) | (next & 0x3F);
        }
        if(valid && ((length == 3 && c < 0x800) || (length == 4 && (c < 0x10000 || c > 0x10FFFF))))
            valid = false;
        if(!valid)
        {
            out += utf8[i];
            i++;
            continue;
        }
        i += length;
        c = to_lower(c);
        if(plain)
        {
            if(is_combining_mark(c))
                continue;
            if(c == 0xDF) // ß
            {
                out += "ss";
                continue;
            }
            c = to_plain(c);
        }
        append_utf8(out, c);
    }
    return out;
}


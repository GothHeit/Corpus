#!/bin/sh
# The key that signs releases (ECDSA P-256, made with openssl). The private key lives in ~/.corpus-release-key, outside
# the repository, and is never committed: back that folder up somewhere safe, because a lost key means every installed
# Corpus has to be updated by hand once (the public half is built into the program).
#
# Usage: tools/release-key.sh          make the key pair if it is missing, then write apps/gui/update_key.hpp from it
set -e
here=$(cd "$(dirname "$0")" && pwd)
dir=${CORPUS_RELEASE_KEY_DIR:-$HOME/.corpus-release-key}
header="$here/../apps/gui/update_key.hpp"

if [ ! -f "$dir/private.pem" ]; then
  umask 077
  mkdir -p "$dir"
  chmod 700 "$dir"
  openssl ecparam -name prime256v1 -genkey -noout -out "$dir/private.pem"
  chmod 600 "$dir/private.pem"
  openssl ec -in "$dir/private.pem" -pubout -out "$dir/public.pem" 2>/dev/null
  echo "Made a new release key in $dir. Back this folder up somewhere safe." >&2
fi

# The public key as BCrypt wants it (BCRYPT_ECCPUBLIC_BLOB): "ECS1", the size of one coordinate, then X and Y.
point=$(openssl ec -in "$dir/private.pem" -pubout -outform DER 2>/dev/null | tail -c 64 | od -An -v -tx1 | tr -d ' \n')
[ ${#point} -eq 128 ] || { echo "could not read the public key" >&2; exit 1; }
{
  echo "#ifndef UPDATE_KEY_HPP"
  echo "#define UPDATE_KEY_HPP"
  echo
  echo "// Generated by tools/release-key.sh: the public half of the key that signs releases, as a BCRYPT_ECCPUBLIC_BLOB for"
  echo "// ECDSA P-256 (magic ECS1, 32-byte coordinates, X then Y). The private half is not in the repository."
  echo "static const unsigned char kUpdatePublicKey[72] = {"
  echo "    0x45, 0x43, 0x53, 0x31, 0x20, 0x00, 0x00, 0x00,"
  echo "$point" | sed 's/../0x&, /g' | fold -w 96 | sed 's/^/    /; s/ *$//'
  echo "};"
  echo
  echo "#endif"
} > "$header"
echo "$header"
